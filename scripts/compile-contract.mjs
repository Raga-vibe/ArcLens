// Compiles contracts/ArcLensRegistry.sol with solc-js and writes the ABI and
// bytecode to src/lib/arc/registry-artifact.ts. Run: npm run compile:contract
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solc = require("solc");

const source = readFileSync(new URL("../contracts/ArcLensRegistry.sol", import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: { "ArcLensRegistry.sol": { content: source } },
  settings: {
    // Arc is EVM-equivalent to Ethereum Osaka; cancun is a conservative target.
    evmVersion: "cancun",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const c = out.contracts["ArcLensRegistry.sol"].ArcLensRegistry;
const bytecode = `0x${c.evm.bytecode.object}`;

// Deterministic CREATE2 deployment through the canonical factory
// (0x4e59…956c, verified present on Arc mainnet), so the registry address is
// known before it is deployed. Changing the contract changes the address.
const { getContractAddress, keccak256, stringToBytes } = await import("viem");
const factory = "0x4e59b44847b379578588920ca78fbf26c0b4956c";
const salt = keccak256(stringToBytes("arclens.registry.v1"));
const address = getContractAddress({ opcode: "CREATE2", from: factory, salt, bytecode }).toLowerCase();

const file = `// Generated by scripts/compile-contract.mjs from contracts/ArcLensRegistry.sol.
// Compiler: solc ${solc.version()} · evmVersion cancun · optimizer 200 runs. Do not edit.

export const registryAbi = ${JSON.stringify(c.abi, null, 2)} as const;

export const registryBytecode = "${bytecode}" as const;

/** Canonical deterministic-deployment factory (CREATE2), same address on most EVM chains. */
export const create2Factory = "${factory}" as const;
/** keccak256("arclens.registry.v1") */
export const registrySalt = "${salt}" as const;
/** Where ArcLensRegistry lives once deployed through the factory with this salt. */
export const registryPredictedAddress = "${address}" as const;
`;
writeFileSync(new URL("../src/lib/arc/registry-artifact.ts", import.meta.url), file);
console.log(`ok: ${c.abi.length} ABI entries, ${bytecode.length / 2 - 1} bytes, CREATE2 address ${address}`);
